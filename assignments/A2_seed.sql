DROP TABLE IF EXISTS tea_orders;
CREATE TABLE tea_orders (
    order_id     INT           NOT NULL PRIMARY KEY,
    ordered_at   DATETIME      NOT NULL,
    branch       VARCHAR(20)   NOT NULL,             -- 'สามย่าน', 'บางนา'
    channel      VARCHAR(10)   NOT NULL,             -- walk_in / grab / lineman
    menu         VARCHAR(50)   NOT NULL,
    size         CHAR(1)       NOT NULL,             -- M / L
    sweetness    TINYINT       NOT NULL,             -- 0 / 25 / 50 / 100 (%)
    qty          INT           NOT NULL,
    unit_price   DECIMAL(8,2)  NOT NULL,
    discount     DECIMAL(8,2)  NOT NULL DEFAULT 0,   -- ส่วนลดทั้งออเดอร์ (บาท)
    member_id    INT           NULL,                 -- NULL = ไม่ใช่สมาชิก
    rating       TINYINT       NULL                  -- 1-5, NULL = ไม่ได้ให้คะแนน
);

